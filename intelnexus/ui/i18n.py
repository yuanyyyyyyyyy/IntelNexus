def get_text(key):
    lang_code = st.session_state.get("lang", "zh")
    search = _SEARCH_LANG.get(lang_code, {})
    if key in search:
        return search[key]
    briefing = _BRIEFING_ZH if lang_code == "zh" else _BRIEFING_EN
    if key in briefing:
        return briefing[key]
    # 兜底：先看搜索中文表，再看简报中文表，否则返回 key
    return _SEARCH_LANG.get("zh", {}).get(key, _BRIEFING_ZH.get(key, key))
