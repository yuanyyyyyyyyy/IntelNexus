def get_tor_proxy_port():
    """获取Tor代理端口（与 darkweb.py 保持一致）"""
    custom_port = os.getenv("TOR_PROXY_PORT")
    if custom_port:
        try:
            return int(custom_port)
        except Exception:
            pass
    return 9150
