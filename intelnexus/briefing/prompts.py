def get_prompt(prompt_name: str, **kwargs) -> str:
    """
    获取并格式化提示词

    Args:
        prompt_name: 提示词名称
        **kwargs: 格式化参数；额外的 kb_context（可选）会在模板
            格式化后追加「历史知识库收藏」参考段，模板无需占位符

    Returns:
        str: 格式化后的提示词
    """
    prompts = {
        "top3": TOP3_PROMPT,
        "ai_dynamic": AI_DYNAMIC_PROMPT,
        "cyber_dynamic": CYBER_DYNAMIC_PROMPT,
        "cve_table": CVE_TABLE_PROMPT,
        "insight": INSIGHT_PROMPT,
        "links": LINKS_PROMPT,
        "policy": POLICY_PROMPT,
        "attack_analysis": ATTACK_ANALYSIS_PROMPT,
        "protection": PROTECTION_PROMPT,
    }

    kb_context = kwargs.pop("kb_context", "")
    prompt = prompts.get(prompt_name, "")
    if prompt and kwargs:
        prompt = prompt.format(**kwargs)
    if prompt and kb_context:
        prompt += (
            "\n\n=== 用户历史知识库收藏（关联参考） ===\n"
            "如果本期内容与下列历史收藏相关，请在相应条目中标注「📚 关联历史收藏」；"
            "无关则忽略，不要生搬硬套：\n" + kb_context + "\n"
        )
    return prompt
