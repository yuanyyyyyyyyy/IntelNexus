def clean():
    """清理构建产物。"""
    for d in [DIST_DIR, BUILD_DIR]:
        if d.exists():
            print(f"Cleaning {d}...")
            shutil.rmtree(d)
    if SPEC_FILE.exists():
        SPEC_FILE.unlink()
    print("Clean done.")


def generate_spec() -> Path:
    """生成 PyInstaller spec 文件。"""
    # 构建 data_files 列表
    data_args = []
    for src, dst in DATA_FILES:
        src_path = ROOT / src
        if src_path.exists():
            data_args.append(f"(r'{src_path}', r'{dst}')")

    data_str = ",\n        ".join(data_args)

    excludes_str = ",\n        ".join(f"'{e}'" for e in EXCLUDES)
    hidden_str = ",\n        ".join(f"'{h}'" for h in HIDDEN_IMPORTS)
    hooks_str = ",\n        ".join(f"r'{h}'" for h in RUNTIME_HOOKS if os.path.exists(h))

    spec_content = f"""# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build_exe.py

a = Analysis(
    [r'{ROOT / "main.py"}'],
    pathex=[r'{ROOT}'],
    binaries=[],
    datas=[
        {data_str},
    ],
    hiddenimports=[
        {hidden_str},
    ],
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[
        {hooks_str},
    ],
    excludes=[
        {excludes_str},
    ],
    noarchive=False,
)

pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='IntelNexus',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    console=True,
    icon=None,
)

coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=False,
    upx=True,
    upx_exclude=[],
    name='IntelNexus',
)
"""
    SPEC_FILE.write_text(spec_content, encoding="utf-8")
    print(f"Generated spec: {SPEC_FILE}")
    return SPEC_FILE


def _copy_post_build_assets():
    """Copy launcher, docs, and create a quick-start README in dist/."""
    dist_root = DIST_DIR / "IntelNexus"
    if not dist_root.exists():
        print("WARNING: dist/IntelNexus not found, skipping post-build assets.")
        return

    # 1. Copy launcher.bat (EXE distribution entry point)
    launcher_src = ROOT / "launcher.bat"
    if launcher_src.exists():
        shutil.copy2(launcher_src, dist_root / "launcher.bat")
        print("  Copied launcher.bat")

    # 2. Copy USER_GUIDE.md (non-technical user documentation)
    guide_src = ROOT / "USER_GUIDE.md"
    if guide_src.exists():
        shutil.copy2(guide_src, dist_root / "USER_GUIDE.md")
        print("  Copied USER_GUIDE.md")

    # 3. Create a quick-start README in the dist folder
    readme_content = """IntelNexus - AI Multi-Source Intelligence Platform
================================================

Quick Start:
  1. Double-click "launcher.bat" to start
  2. Browser will open automatically
  3. Follow the on-screen guide to configure AI model

First Time Setup:
  - You need an AI model (cloud API or local Ollama)
  - Cloud API (recommended for beginners): DeepSeek / Moonshot / Qwen
  - Local model (free): Install Ollama from https://ollama.com

For detailed instructions, see USER_GUIDE.md

Project: https://github.com/yuanyyyyyyyyy/IntelNexus
"""
    (dist_root / "README.txt").write_text(readme_content, encoding="utf-8")
    print("  Created README.txt")


def build(spec_file: Path):
    """Run PyInstaller build."""
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm",
        "--clean",
        str(spec_file),
    ]
    print(f"Running: {' '.join(cmd)}")
    result = subprocess.run(cmd, cwd=str(ROOT))
    if result.returncode != 0:
        print(f"ERROR: PyInstaller exited with code {result.returncode}")
        sys.exit(1)

    exe_path = DIST_DIR / "IntelNexus" / "IntelNexus.exe"
    if exe_path.exists():
        size_mb = exe_path.stat().st_size / (1024 * 1024)
        print(f"\nBuild successful!")
        print(f"Output: {exe_path}")
        print(f"Size: {size_mb:.1f} MB")
    else:
        print(f"\nWARNING: Expected output not found at {exe_path}")
        print("Check build output above for errors.")
        return

    # Copy post-build assets (launcher, docs, README)
    print("\nCopying post-build assets...")
    _copy_post_build_assets()


def main():
    parser = argparse.ArgumentParser(description="Build IntelNexus EXE")
    parser.add_argument("--clean", action="store_true", help="Clean before build")
    parser.add_argument("--spec-only", action="store_true", help="Only generate spec, don't build")
    args = parser.parse_args()

    if args.clean:
        clean()

    spec_file = generate_spec()

    if args.spec_only:
        print("Spec file generated. Run without --spec-only to build.")
        return

    build(spec_file)


if __name__ == "__main__":
    main()
