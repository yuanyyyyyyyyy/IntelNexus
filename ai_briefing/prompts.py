def get_prompt(prompt_name: str, **kwargs) -> str:
    """
    获取并格式化提示词
    
    Args:
        prompt_name: 提示词名称
        **kwargs: 格式化参数
    
    Returns:
        str: 格式化后的提示词
    """
    prompts = {
        "top3": TOP3_PROMPT,
        "gov_usage": GOV_USAGE_PROMPT,
        "china_narrative": CHINA_NARRATIVE_PROMPT,
        "legislation": LEGISLATION_PROMPT,
        "data_leak": DATA_LEAK_PROMPT,
        "insight": INSIGHT_PROMPT,
        "full_briefing": FULL_BRIEFING_PROMPT
    }
    
    prompt = prompts.get(prompt_name, "")
    if prompt and kwargs:
        return prompt.format(**kwargs)
    return prompt
